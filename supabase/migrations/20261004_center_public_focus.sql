-- תחום המרכז - מה שמופיע בכותרת העמוד הציבורי במקום "מרכז טיפולי".
--
-- כותרת עמוד המרכז נבנתה תמיד כ"<שם> - מרכז טיפולי ב<עיר>". מרכז ששמו כבר
-- אומר במה הוא עוסק ("... - טיפול רגשי ופרא רפואי") לא הפסיד מזה כלום. מרכז
-- ששמו הוא רק שם נשאר עם כותרת שאין בה אף מילה שמחפשים: ב-90 הימים שעד
-- 4/10/2026 עמוד של מרכז שעוסק בטיפול זוגי ומיני הופיע בגוגל רק בחיפושי שם
-- המרכז, ופעמיים בלבד בחיפוש שיש בו "זוגי".
--
-- public_focus הוא תחום העיסוק של המרכז בכמה מילים ("טיפול זוגי ומיני"). כשהוא
-- מלא הוא מחליף את "מרכז טיפולי" בכותרת ובשורה שמעל שם המרכז. ריק = כמו קודם.
-- אין מילוי לאחור: הערך נכנס רק כשכותבים אותו במפורש, מהאדמין.
alter table public.therapy_center_accounts
  add column if not exists public_focus text;

comment on column public.therapy_center_accounts.public_focus is
  'תחום העיסוק של המרכז בכמה מילים (עד 40 תווים), למשל "טיפול זוגי ומיני". מחליף את "מרכז טיפולי" בכותרת העמוד הציבורי ובשורה שמעל שם המרכז. ריק = "מרכז טיפולי".';

grant select, insert, update on public.therapy_center_accounts to service_role;
