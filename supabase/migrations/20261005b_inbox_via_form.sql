-- פנייה שהגיעה לסוכן השירות דרך טופס באתר, ולא במייל ישיר.
--
-- טופס "צור קשר" (וטופס "בית למפתחים") שולחים אלינו מייל מהכתובת של האתר עצמו,
-- עם Reply-To של הגולש. הסוכן דילג על כל מייל מהדומיינים שלנו, ולכן עד
-- 5/10/2026 הפניות האלה לא נכנסו לתור שלו בכלל: לא סווגו ולא נוסחה להן טיוטה.
-- מעכשיו הן נקלטות על שם הגולש (from_email = ה-Reply-To), והעמודה הזו מסמנת
-- מאיזה טופס הגיעו.
--
-- via_form   'contact' / 'developers'; ריק = מייל רגיל. בלי CHECK בכוונה: טופס
--            נוסף בקוד לא צריך להיתקע על אילוץ בטבלה.
--
-- למה צריך את הסימון ולא מספיק שהשורה קיימת: שתי התראות של אותו טופס יכולות
-- לשבת באותו שרשור ב-Gmail (אותו שולח, אותו נושא), ואז "הודעה חדשה יותר
-- בשרשור" או "יצאה תשובה בשרשור" אינם ראיה שהפנייה הזו טופלה. בשורות עם
-- via_form הבדיקות האלה דורשות גם את הכתובת של הפונה.
alter table public.inbox_messages
  add column if not exists via_form text;

comment on column public.inbox_messages.via_form is
  'מאיזה טופס באתר הגיעה הפנייה: contact / developers. ריק = מייל ישיר. בשורות כאלה from_email הוא ה-Reply-To של הגולש, לא כתובת השולח של האתר.';

grant select, insert, update on public.inbox_messages to service_role;
