/**
 * הצורה המותאמת למגדר של תואר מקצועי. מגדר לא ידוע או תואר שאינו במפה -
 * מוחזר הערך הקנוני כפי שהוא (הצורה הכוללת).
 */
export function genderTitle(title: string, gender: string | null | undefined): string {
  const forms = TITLE_FORMS[title];
  if (!forms) return title;
  if (gender === "נקבה") return forms.f;
  if (gender === "זכר") return forms.m;
  return title;
}

/** ממיר מערך תארים מקצועיים בהתאם למגדר */
export function genderTitles(titles: string[], gender: string | null | undefined): string[] {
  return titles.map((t) => genderTitle(t, gender));
}

// ── התואר הציבורי: "מטפל/ת בהבעה ויצירה" שמטפל/ת גם במבוגרים ─────────────
//
// החלטת הבעלים (20/8/2026): בכותרת הפרופיל הציבורי מוצג "פסיכותרפיסט/ית",
// והתואר המדויק נשאר בשורת "הכשרה" בגוף העמוד. כלומר שום דבר לא נמחק -
// הכותרת אומרת מה המטפל/ת עושה בשפה שמטופל מחפש ומבין, והפרטים נושאים את
// ההסמכה כלשונה.
//
// שלושה גבולות שהכלל הזה לא חוצה:
//   1. **הנתונים לא משתנים.** therapist_types נשאר "מטפל/ת בהבעה ויצירה"
//      בבסיס הנתונים, בטפסי ההרשמה והעריכה, ובמנוע ההתאמה (משקל 8 + סינון
//      קשיח). זו שכבת תצוגה בלבד.
//   2. **רק מי שמטפל/ת במבוגרים.** מי שמסומן/ת לילדים/גיל רך בלבד ממשיך/ה
//      להופיע כמטפל/ת בהבעה ויצירה - שם התואר המקורי הוא המדויק.
//   3. **מרכזים לא נכללים.** ישות-מרכז מציגה את סוגי המטפלים שלה כרשימה
//      ולא עוברת דרך הפונקציות כאן; מרכז אינו "פסיכותרפיסט".
const EXPRESSIVE_ARTS_TYPE = "מטפל/ת בהבעה ויצירה";

// "הגיל השלישי" נכלל כי גם הוא מבוגרים. בפועל כל מי שסימן אותו סימן גם
// "מבוגרים", אבל הכלל לא צריך להישען על צירוף מקרים בנתונים.
const ADULT_AGE_GROUPS = ["מבוגרים", "הגיל השלישי"];

const PSYCHOTHERAPIST = {
  m: "פסיכותרפיסט",
  f: "פסיכותרפיסטית",
  // מגדר ריק או לא ידוע - צורה כוללת, כמו שאר הערכים הקנוניים בטבלה.
  neutral: "פסיכותרפיסט/ית",
};

export function treatsAdults(ageGroups: string[] | null | undefined): boolean {
  return (ageGroups ?? []).some((g) => ADULT_AGE_GROUPS.includes(g));
}

/**
 * הכלל היחיד, במקום אחד: מחזיר את התואר הציבורי החלופי, או null כשהכלל
 * אינו חל. כל מסלול שמציג תואר בכותרת קורא לו קודם, כדי ששני עמודים לא
 * יציגו את אותו מטפל אחרת.
 */
export function publicTypeOverride(
  type: string,
  gender: string | null | undefined,
  ageGroups: string[] | null | undefined
): string | null {
  if (type !== EXPRESSIVE_ARTS_TYPE) return null;
  if (!treatsAdults(ageGroups)) return null;
  if (gender === "נקבה") return PSYCHOTHERAPIST.f;
  if (gender === "זכר") return PSYCHOTHERAPIST.m;
  return PSYCHOTHERAPIST.neutral;
}

/**
 * התואר כפי שהוא מוצג בכותרת ציבורית (H1, <title>, כרטיס, schema.org).
 * לשורת "הכשרה" בגוף הפרופיל משתמשים ב-genderTitle הישיר - שם ההסמכה
 * המדויקת היא כל הנקודה.
 */
export function publicTherapistTitle(
  type: string,
  gender: string | null | undefined,
  ageGroups: string[] | null | undefined
): string {
  return publicTypeOverride(type, gender, ageGroups) ?? genderTitle(type, gender);
}
