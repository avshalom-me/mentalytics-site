/** שם אזור מלא ("צפון השרון") → מפתח הקבוצה הגס ("sharon"). */
export function regionGroupOf(region: string): string {
  const r = String(region ?? "").trim();
  if (!r) return "other";
  for (const [key, members] of Object.entries(REGION_GROUPS)) {
    if (members.includes(r)) return key;
  }
  // נפילה לתאימות עם המיפוי ההיסטורי של האנליטיקה, שעבד על הכלה בטקסט.
  if (r.includes("גוש דן") || r.includes("שפלה")) return "center";
  if (r.includes("שרון")) return "sharon";
  if (r.includes("ירושלים")) return "jerusalem";
  if (r.includes("חיפה") || r.includes("קריות")) return "haifa";
  if (r.includes("גליל") || r.includes("עמק")) return "north";
  if (r.includes("דרום") || r.includes("באר שבע") || r.includes("אשדוד") || r.includes("אשקלון")) return "south";
  return "other";
}

// ── Region <-> URL-slug helpers (pure; safe for client + server) ──────────────
// Hebrew region names with spaces become hyphenated slugs (percent-encoded in
// the URL, which Google handles fine and which matches Hebrew search queries).
export const ONLINE_SLUG = "אונליין";

export function regionToSlug(region: string): string {
  return region.trim().replace(/\s+/g, "-");
}

export function slugToRegion(slug: string): string | null {
  let decoded: string;
  try {
    decoded = decodeURIComponent(slug);
  } catch {
    return null; // malformed (e.g. non-UTF-8) encoding → treat as not found
  }
  return ALL_REGIONS.find((r) => regionToSlug(r) === decoded) ?? null;
}

// Every city in the vocabulary gets its own landing page (was a curated list
// of 20 majors - which left high-supply towns like פרדס חנה-כרכור with no page
// at all). Thin-page protection lives elsewhere and keeps this safe:
//   - pages with fewer than MIN_LISTED_FOR_INDEX therapists are noindex,
//   - the sitemap only includes cities at/above that threshold,
// so a city page becomes indexable automatically the moment supply fills in.
export const CITY_SEO_LIST: readonly string[] = Object.values(REGION_CITIES).flat();

export function slugToCity(slug: string): string | null {
  let decoded: string;
  try {
    decoded = decodeURIComponent(slug);
  } catch {
    return null;
  }
  return (CITY_SEO_LIST as readonly string[]).find((c) => regionToSlug(c) === decoded) ?? null;
}
