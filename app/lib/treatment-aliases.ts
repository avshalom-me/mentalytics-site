// מפתחות המלצה של השאלונים שאינם תחום טיפול בטופס של המטפלים, והתחום שמטפל
// מסמן עבורם.
//
// למה: מנוע ההתאמה משווה את מפתח ההמלצה לתחומי הטיפול של המטפל בשוויון מדויק.
// שאלון הילדים ממליץ על "הדרכת הורים טיפולית", ובטופס של המטפלים יש רק "הדרכת
// הורים" - ולכן מ-3/5/2026 אף מטפל לא קיבל ניקוד מומחיות על ההמלצה הזו: כולם
// יצאו 38%, בסדר שלא היה קשור לשאלה אם הם בכלל עושים הדרכת הורים (נמדד
// 21/9/2026 על השרת החי; אותו חיפוש עם "הדרכת הורים" החזיר 9 מ-10 ב-100%).
//
// ההמרה נעשית בחיפוש בלבד. המפתח עצמו נשאר כמו שהוא בשאלון, בדוח ובנתוני
// המחקר - "טיפולית" הוא חלק מההמלצה שההורה קורא, ושינוי שלו היה משנה גם את
// חותמת הגרסה של השאלון (kids-recommendations.ts נמצא ב-QUIZ_INSTRUMENT_FILES).
//
// מפתח חדש שאינו תחום בטופס נתפס בבדיקה ב-treatment-aliases.test.ts.

const ALIASES: Readonly<Record<string, string>> = {
  "הדרכת הורים טיפולית": "הדרכת הורים",
};

function norm(s: string): string {
  return s.trim().toLowerCase().replace(/\s+/g, " ");
}

const NORMALIZED = new Map(Object.entries(ALIASES).map(([k, v]) => [norm(k), v]));

/** התחום בטופס שמטפל מסמן עבור מפתח ההמלצה; מפתח שאינו כינוי חוזר כמו שהוא. */
export function toTrainingAreaKey(key: string): string {
  return NORMALIZED.get(norm(key)) ?? key;
}

export const TREATMENT_KEY_ALIASES = ALIASES;
