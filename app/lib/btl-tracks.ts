/**
 * מסלולי הביטוח הלאומי לטיפול נפשי ופרה-רפואי.
 *
 * Split into a page per track rather than one long guide: someone who was hurt
 * at work and someone whose child was just diagnosed share almost no vocabulary,
 * no forms and no committee. A single page would have forced both of them to
 * read past the other's route, and would have competed with itself for every
 * one of the queries below.
 *
 * SOURCING RULE FOR THIS FILE - do not relax it.
 * Every number here (form number, session count, appeal window, ₪ ceiling) was
 * read on btl.gov.il or kolzchut.org.il. A multi-model panel run on 4/8/2026
 * produced several confident, plausible and WRONG figures - session counts the
 * official page does not state, an eligibility threshold off by 10 points, and
 * fabricated effect sizes. Entitlement content is where a wrong number does
 * real harm to someone who is already unwell. If a figure cannot be pointed at
 * a source, it does not go in - `sessionsNote` says "נקבע על ידי עובד השיקום"
 * instead, which is what the official page actually says.
 */

export type TrackStep = { title: string; body: string; form?: string };
export type TrackIssue = { problem: string; whatToDo: string };

export type BtlTrack = {
  slug: string;
  /** Short label for breadcrumbs, cards and cross-links. */
  name: string;
  /** H1 / <title>, in searcher phrasing. */
  searchTitle: string;
  metaDescription: string;
  /** One paragraph: who this track is for. Written to let a reader self-select. */
  whoFor: string;
  /** What the NII actually pays for on this track - the honest scope. */
  covered: string;
  /** null when the track funds no therapy directly (a common misconception). */
  fundsTherapyDirectly: boolean;
  steps: TrackStep[];
  /** Ordered forms with their official titles. */
  forms: { number: string; title: string }[];
  /** Who decides. */
  decidedBy: string;
  /** Appeal windows - the single most time-critical thing on the page. */
  appeals: { against: string; window: string; to: string }[];
  issues: TrackIssue[];
  /** Directory pages this track routes to. */
  directory: { href: string; label: string }[];
  /** Sits under the session-count question, where the official pages are silent. */
  sessionsNote: string;
  /**
   * The clinical half of the page, and deliberately the part a reader meets
   * first. Someone landing here is usually mid-crisis and reading about forms;
   * opening with bureaucracy tells them their difficulty is an administrative
   * problem. Written in plain language with no effect sizes - the evidence
   * lives on the hub, and a person deciding whether their reaction is "bad
   * enough" to deserve help is not helped by a confidence interval.
   */
  whyHelp: { heading: string; paragraphs: string[]; signs: string[] };
  /** Official pages, embedded inside the bureaucratic section. */
  officialLinks: { label: string; href: string }[];
  /** Closing recap - what to actually do, in order. */
  summary: string[];
};

