// תווית ההתאמה לכרטיס שמחוץ לאזור שבחר המטופל.
//
// ב-19/8/2026 המרחק יצא מהציון המוצג, ומאז כרטיס של מטפל מחדרה הראה 99%
// ליד כרטיס של מטפל מחיפה עם 94%, על שאלון שהתחיל ב"חיפה". המספר היה נכון
// לפי ההגדרה (התאמה מקצועית בלבד) ומטעה לפי הקריאה: מטופל לא משווה הגדרות,
// הוא משווה מספרים. במקום תקרה מלאכותית על המספר - שהייתה שקר מסוג אחר, כי
// ההתאמה המקצועית באמת מלאה - הכרטיס שמחוץ לאזור מקבל מילים: דרגת ההתאמה
// המקצועית, ולצידה למה הוא בכלל ברשימה (אזור סמוך / אונליין). הציון עצמו
// נשאר בנתונים, לצורך ההסבר "למה הותאם לי" ולמדידה.
//
// משותף לשני השאלונים, כדי שהדרגות יישארו זהות.

export function professionalFitLabel(score: number | null | undefined): string {
  if (score == null) return "התאמה מקצועית";
  if (score >= 85) return "התאמה מקצועית גבוהה";
  if (score >= 70) return "התאמה מקצועית טובה";
  return "התאמה מקצועית חלקית";
}

/** למה הכרטיס מופיע למרות שאינו באזור: אונליין (רק אם המטופל ביקש) או אזור סמוך. */
export function outOfAreaReason(onlineRequested: boolean, therapistOnline: boolean | null | undefined): string {
  return onlineRequested && therapistOnline ? "אונליין" : "אזור סמוך";
}
