/** מרחק אווירי בק"מ (Haversine). לצורך דירוג בלבד. */
export function distanceKm(a: LatLng, b: LatLng): number {
  const R = 6371;
  const toRad = (x: number) => (x * Math.PI) / 180;
  const dLat = toRad(b[0] - a[0]);
  const dLng = toRad(b[1] - a[1]);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(a[0])) * Math.cos(toRad(b[0])) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

/** המרחק הקצר ביותר בין עיר המטופל לאחת הערים שהמטפל רשם. null כשאין קואורדינטה. */
export function nearestKm(patientCity: string, therapistCities: string[]): number | null {
  const p = CITY_COORDS[patientCity];
  if (!p) return null;
  let best: number | null = null;
  for (const c of therapistCities) {
    const t = CITY_COORDS[c];
    if (!t) continue;
    const d = distanceKm(p, t);
    if (best == null || d < best) best = d;
  }
  return best;
}
