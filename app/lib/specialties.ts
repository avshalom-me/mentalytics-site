// the existing TRAINING_AREAS list (what therapists actually tag themselves
// with), so a page exists for every specialty and fills up on its own.
// Thin-page protection mirrors the city pages: <MIN_LISTED_FOR_INDEX listed →
// noindex + out of the sitemap.

export const SPECIALTY_LIST: readonly string[] = TRAINING_AREAS;

export function specialtyToSlug(s: string): string {
  return s.trim().replace(/\s+/g, "-");
}

export function slugToSpecialty(slug: string): string | null {
  let decoded: string;
  try {
    decoded = decodeURIComponent(slug);
  } catch {
    return null;
  }
  return SPECIALTY_LIST.find((s) => specialtyToSlug(s) === decoded) ?? null;
}

